// What Windows' broadcast window tells Island (msgwin.rs), on a Mac: the clipboard changing (the
// general pasteboard's change count, read twice a second), drives arriving and leaving (/Volumes),
// and the screens changing (their layout, read with the clipboard). Power changes are read in
// mac/system.rs.

use std::ffi::CStr;
use std::path::Path;
use std::sync::atomic::{AtomicIsize, Ordering};
use std::sync::OnceLock;
use std::time::Duration;

use objc2::rc::autoreleasepool;
use objc2::runtime::AnyObject;
use objc2::{class, msg_send};
use serde::Serialize;
use tauri::{AppHandle, Emitter};

use crate::overlay::LABEL as ISLAND;

static APP: OnceLock<AppHandle> = OnceLock::new();
/// The change count after Island's own copy (a Copy button): that change isn't news.
static OWN_WRITE: AtomicIsize = AtomicIsize::new(-1);

#[derive(Serialize, Clone)]
#[serde(rename_all = "camelCase")]
struct ClipboardEvent {
    seq: u32,
    kind: &'static str,
    text: Option<String>,
    files: Vec<String>,
    excluded: bool,
}

#[derive(Serialize, Clone)]
#[serde(rename_all = "camelCase")]
struct DeviceEvent {
    kind: &'static str,
    action: &'static str,
    /// A Mac: the volume's name (it lives at /Volumes/<name>).
    drive: String,
    label: String,
    removable: bool,
}

// ------------------------------------------------------------------ the pasteboard

pub fn nsstring(s: &str) -> *mut AnyObject {
    let c = std::ffi::CString::new(s.replace('\0', "")).unwrap_or_default();
    unsafe { msg_send![class!(NSString), stringWithUTF8String: c.as_ptr()] }
}

pub fn rust_string(s: *mut AnyObject) -> Option<String> {
    if s.is_null() {
        return None;
    }
    let p: *const libc::c_char = unsafe { msg_send![s, UTF8String] };
    (!p.is_null()).then(|| unsafe { CStr::from_ptr(p) }.to_string_lossy().to_string())
}

fn pasteboard() -> *mut AnyObject {
    unsafe { msg_send![class!(NSPasteboard), generalPasteboard] }
}

pub fn change_count() -> isize {
    let pb = pasteboard();
    if pb.is_null() {
        return 0;
    }
    unsafe { msg_send![pb, changeCount] }
}

/// The type names on the pasteboard now ("public.utf8-plain-text", "public.file-url"…).
fn types(pb: *mut AnyObject) -> Vec<String> {
    let list: *mut AnyObject = unsafe { msg_send![pb, types] };
    if list.is_null() {
        return Vec::new();
    }
    let n: usize = unsafe { msg_send![list, count] };
    (0..n).filter_map(|i| rust_string(unsafe { msg_send![list, objectAtIndex: i] })).collect()
}

fn string_for(pb: *mut AnyObject, kind: &str) -> Option<String> {
    rust_string(unsafe { msg_send![pb, stringForType: nsstring(kind)] })
}

/// "file:///Users/me/My%20File.txt" → "/Users/me/My File.txt".
pub fn file_url_path(url: &str) -> Option<String> {
    let rest = url.strip_prefix("file://")?;
    let rest = rest.strip_prefix("localhost").unwrap_or(rest);
    let bytes = rest.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%' && i + 2 < bytes.len() {
            if let Ok(b) = u8::from_str_radix(&rest[i + 1..i + 3], 16) {
                out.push(b);
                i += 3;
                continue;
            }
        }
        out.push(bytes[i]);
        i += 1;
    }
    let path = String::from_utf8(out).ok()?;
    Some(path.trim_end_matches('/').to_string()).filter(|p| !p.is_empty())
}

/// The files copied in the Finder (each item's file URL).
fn files(pb: *mut AnyObject, max: usize) -> Vec<String> {
    let items: *mut AnyObject = unsafe { msg_send![pb, pasteboardItems] };
    if items.is_null() {
        return Vec::new();
    }
    let n: usize = unsafe { msg_send![items, count] };
    let kind = nsstring("public.file-url");
    (0..n.min(max))
        .filter_map(|i| {
            let item: *mut AnyObject = unsafe { msg_send![items, objectAtIndex: i] };
            rust_string(unsafe { msg_send![item, stringForType: kind] }).and_then(|u| file_url_path(&u))
        })
        .collect()
}

/// Password managers mark what they copy (nspasteboard.org's concealed and transient types), as
/// Windows apps do with ExcludeClipboardContentFromMonitorProcessing.
fn excluded(t: &[String]) -> bool {
    t.iter().any(|k| k == "org.nspasteboard.ConcealedType" || k == "org.nspasteboard.TransientType" || k == "org.nspasteboard.AutoGeneratedType")
}

fn on_clipboard(app: &AppHandle, count: isize) {
    let pb = pasteboard();
    if pb.is_null() {
        return;
    }
    let t = types(pb);
    let ex = excluded(&t);
    let has = |k: &str| t.iter().any(|x| x == k);
    let (kind, text, list) = if ex {
        ("other", None, Vec::new())
    } else if has("public.file-url") {
        ("files", None, files(pb, 50))
    } else if has("public.utf8-plain-text") {
        ("text", string_for(pb, "public.utf8-plain-text").map(|s| s.chars().take(20_000).collect()), Vec::new())
    } else if has("public.png") || has("public.tiff") || has("public.jpeg") {
        ("image", None, Vec::new())
    } else {
        ("other", None, Vec::new())
    };
    let _ = app.emit_to(ISLAND, "clipboard", ClipboardEvent { seq: count as u32, kind, text, files: list, excluded: ex });
}

/// Island's own copy: the next change is ours.
pub fn wrote_clipboard() {
    OWN_WRITE.store(change_count(), Ordering::Relaxed);
}

// ------------------------------------------------------------------ drives

/// The volumes under /Volumes that are drives the user plugged in (not this Mac's own disk).
fn volumes() -> Vec<(String, bool)> {
    let Ok(entries) = std::fs::read_dir("/Volumes") else { return Vec::new() };
    let mut out: Vec<(String, bool)> = entries
        .flatten()
        .filter_map(|e| {
            let name = e.file_name().to_string_lossy().to_string();
            let path = e.path();
            // The startup disk shows here as a link to /.
            if name.starts_with('.') || std::fs::read_link(&path).is_ok() {
                return None;
            }
            Some((name, removable(&path)))
        })
        .collect();
    out.sort();
    out
}

/// A drive of its own (USB stick, SD card, external disk), not a part of the Mac's disk.
fn removable(path: &Path) -> bool {
    let Ok(c) = std::ffi::CString::new(path.to_string_lossy().as_bytes()) else { return false };
    let mut s: libc::statfs = unsafe { std::mem::zeroed() };
    if unsafe { libc::statfs(c.as_ptr(), &mut s) } != 0 {
        return false;
    }
    let local = s.f_flags & libc::MNT_LOCAL as u32 != 0;
    let root = s.f_flags & libc::MNT_ROOTFS as u32 != 0;
    let from: String = s.f_mntfromname.iter().take_while(|c| **c != 0).map(|c| *c as u8 as char).collect();
    // Disk images and the system's own volumes aren't drives someone plugged in.
    local && !root && from.starts_with("/dev/disk") && !path.starts_with("/Volumes/Recovery")
}

// ------------------------------------------------------------------ the loop

fn screens() -> Vec<(i32, i32, u32, u32)> {
    APP.get()
        .and_then(|a| a.available_monitors().ok())
        .map(|ms| ms.iter().map(|m| (m.position().x, m.position().y, m.size().width, m.size().height)).collect())
        .unwrap_or_default()
}

pub fn start(app: AppHandle) {
    let _ = APP.set(app.clone());
    std::thread::spawn(move || {
        let mut count = autoreleasepool(|_| change_count());
        let mut drives = volumes();
        let mut layout: Vec<(i32, i32, u32, u32)> = Vec::new();
        let mut tick = 0u32;
        loop {
            std::thread::sleep(Duration::from_millis(500));
            tick = tick.wrapping_add(1);
            autoreleasepool(|_| {
                let now = change_count();
                if now != count {
                    count = now;
                    if OWN_WRITE.swap(-1, Ordering::Relaxed) != now {
                        on_clipboard(&app, now);
                    }
                }
            });
            // Drives and screens every 2 s.
            if tick % 4 != 0 {
                continue;
            }
            let fresh = volumes();
            for (name, removable) in fresh.iter().filter(|v| !drives.iter().any(|d| d.0 == v.0)) {
                let _ = app.emit_to(ISLAND, "device", DeviceEvent { kind: "volume", action: "arrived", drive: name.clone(), label: String::new(), removable: *removable });
            }
            for (name, _) in drives.iter().filter(|d| !fresh.iter().any(|v| v.0 == d.0)) {
                let _ = app.emit_to(ISLAND, "device", DeviceEvent { kind: "volume", action: "removed", drive: name.clone(), label: String::new(), removable: false });
            }
            drives = fresh;
            let now = screens();
            if !layout.is_empty() && now != layout {
                let _ = app.emit_to(ISLAND, "displays-changed", ());
            }
            layout = now;
        }
    });
}

/// What the clipboard holds for Land's Cmd+V: files copied in the Finder, else text.
#[derive(Serialize, Default)]
pub struct Pasted {
    files: Vec<String>,
    text: Option<String>,
}

#[tauri::command]
pub fn clipboard_paste() -> Pasted {
    autoreleasepool(|_| {
        let pb = pasteboard();
        if pb.is_null() {
            return Pasted::default();
        }
        let t = types(pb);
        if t.iter().any(|k| k == "public.file-url") {
            return Pasted { files: files(pb, 10_000), text: None };
        }
        let text = string_for(pb, "public.utf8-plain-text").map(|s| s.chars().take(20_001).collect::<String>()).filter(|s| !s.trim().is_empty());
        Pasted { files: Vec::new(), text }
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn file_urls_become_paths() {
        assert_eq!(file_url_path("file:///Users/me/My%20File.txt").as_deref(), Some("/Users/me/My File.txt"));
        assert_eq!(file_url_path("file:///Users/me/Folder/").as_deref(), Some("/Users/me/Folder"));
        assert_eq!(file_url_path("file://localhost/tmp/a").as_deref(), Some("/tmp/a"));
        assert_eq!(file_url_path("https://example.com"), None);
    }

    #[test]
    fn password_managers_are_left_out() {
        assert!(excluded(&["org.nspasteboard.ConcealedType".to_string()]));
        assert!(!excluded(&["public.utf8-plain-text".to_string()]));
    }

    #[test]
    fn the_startup_disk_is_not_a_drive() {
        assert!(volumes().iter().all(|(name, _)| !name.starts_with('.')));
    }
}
